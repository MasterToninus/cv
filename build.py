"""Build the CV with Python, pdfLaTeX and Biber; make and Perl are optional."""

from __future__ import annotations

import argparse
import csv
import os
import shutil
import subprocess
import sys
from contextlib import contextmanager
from pathlib import Path

from cvgen.helpers.clock import resolve_date, source_epoch
from cvgen.helpers.formats import (
    DEFAULT_FORMAT,
    FORMAT_CHOICES,
    OUTPUT_STEMS,
    selected_formats,
)
from cvgen.helpers.pagination import find_empty_body_pages
from cvgen.helpers.paths import resolve_project_path

ROOT = Path(__file__).resolve().parent
TOOLS = ("pdflatex", "biber")
LEGACY_CURRENT_STEMS = ("cv", "Cv-Academic-Home")
GENERATED_SUFFIXES = (
    ".tex",
    ".pdf",
    ".aux",
    ".bbl",
    ".bcf",
    ".blg",
    ".log",
    ".out",
    ".run.xml",
    ".fdb_latexmk",
    ".fls",
    ".synctex.gz",
    ".dvi",
    ".toc",
    ".skip.tex",
)


def project_path(value: str | Path) -> Path:
    """Make command-line paths independent of the directory used to invoke Python."""
    return resolve_project_path(value, root=ROOT)


def check_tools(required: tuple[str, ...] = TOOLS) -> dict[str, str]:
    """Resolve tools before generation so a missing compiler fails promptly.

    Industry needs only pdfLaTeX; the other formats also resolve citations
    with Biber. The caller chooses the required tool set before any writes.
    """
    found = {name: shutil.which(name) for name in required}
    missing = [name for name, path in found.items() if path is None]
    if missing:
        raise RuntimeError(
            "Missing tools: "
            + ", ".join(missing)
            + ". Install a TeX distribution with pdfLaTeX and Biber."
        )
    return found


def clean(output_dir: Path) -> None:
    """Remove known CV build products only; never recursively delete a directory."""
    if not output_dir.exists():
        return
    filenames = {"build.log"}
    for stem in (*OUTPUT_STEMS.values(), *LEGACY_CURRENT_STEMS):
        for suffix in GENERATED_SUFFIXES:
            filenames.add((stem + suffix).casefold())
        filenames.add((stem + ".build.log").casefold())
    # Enumerate actual names: older lower-case stems are distinct files on
    # Linux, while Windows aliases them to the newly capitalized output names.
    for path in output_dir.iterdir():
        if path.name.casefold() in filenames and (path.is_file() or path.is_symlink()):
            path.unlink()


def cleanup_legacy_home(output_dir: Path) -> None:
    """Remove previous current-layout names after the replacement PDF succeeds."""
    for stem in LEGACY_CURRENT_STEMS:
        for suffix in GENERATED_SUFFIXES:
            (output_dir / (stem + suffix)).unlink(missing_ok=True)
        (output_dir / (stem + ".build.log")).unlink(missing_ok=True)
    (output_dir / "build.log").unlink(missing_ok=True)


def write_skip_pages(path: Path, pages: tuple[int, ...]) -> None:
    """Discard empty physical pages in TeX so links and numbering stay correct."""
    if any(type(page) is not int or page < 1 for page in pages):
        raise ValueError("Skipped page numbers must be positive integers")
    # Count physical shipout attempts separately from the printed page counter.
    # Discarding a box must also undo Hyperref's absolute/page-label counters,
    # otherwise links and the PDF viewer's page labels drift from visible pages.
    lines = [
        "%+------------------------------------------------------------------------+",
        "%| NOTE: Generated by build.py; physical pages with no body content.",
        "%| DATE: 2026-11-04",
        "%| Author: Antonio Michele Miti",
        "%| Credits: CV generator; generated file, rebuild rather than edit.",
        "%+------------------------------------------------------------------------+",
        r"\newcount\cvshipoutattempt",
        r"\AddToHook{shipout/before}{%",
        r"  \global\advance\cvshipoutattempt by 1",
    ]
    for page in sorted(set(pages)):
        lines.extend(
            (
                rf"  \ifnum\cvshipoutattempt={page}\relax",
                r"    \DiscardShipoutBox\addtocounter{page}{-1}%",
                r"    \ifcsname Hy@abspage\endcsname",
                r"      \global\advance\csname Hy@abspage\endcsname by -1",
                r"    \fi",
                r"    \ifcsname HyPL@LastNumber\endcsname",
                r"      \expandafter\xdef\csname HyPL@LastNumber\endcsname{\number\value{page}}%",
                r"    \fi",
                r"  \fi",
            )
        )
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


@contextmanager
def _preserve_pdf_on_failure(pdf: Path):
    """Restore the previous complete PDF, or remove a failed first build.

    Only the deliverable is rolled back. Auxiliary files and the compiler
    transcript remain available to diagnose the unsuccessful attempt.
    """
    try:
        previous = pdf.read_bytes()
    except FileNotFoundError:
        previous = None
    try:
        yield
    except BaseException:
        # LaTeX writes a provisional PDF before Biber and reference-resolution
        # passes finish. Even an interruption must not publish that partial PDF.
        # Keep compilation in its normal directory to preserve relative paths
        # and reproducible TeX metadata; these CVs are small enough to back up.
        if previous is None:
            pdf.unlink(missing_ok=True)
        else:
            pdf.write_bytes(previous)
        raise


def compile_pdf(
    output_dir: Path, tools: dict[str, str], epoch: str, stem: str | None = None
) -> Path:
    """Compile one generated source and suppress empty dossier pages in TeX.

    Recompilation updates references and page totals without reflowing retained
    pages. Tool failures, timeouts and uncertain pagination stop the build.
    """
    if stem is None:
        stem = OUTPUT_STEMS["current"]
    if not stem or Path(stem).name != stem or stem in {".", ".."}:
        raise ValueError("The compilation stem must be a filename without a directory")
    academic = stem == OUTPUT_STEMS["academic-dossier"]
    skip_path = output_dir / (stem + ".skip.tex")
    if academic:
        # Re-detect from current data; an earlier page list must never be reused.
        skip_path.unlink(missing_ok=True)
    # The same epoch controls TeX timestamps; pinned Python inputs alone cannot
    # guarantee identical PDFs across different TeX installations or fonts.
    environment = os.environ.copy()
    environment.update(SOURCE_DATE_EPOCH=epoch, FORCE_SOURCE_DATE="1", TZ="UTC")
    # Biber's bundled Perl does not accept C.UTF-8 on Windows.
    environment.update(LC_ALL="C", LC_CTYPE="C", LANG="C")
    latex = [
        tools["pdflatex"],
        "-interaction=nonstopmode",
        "-halt-on-error",
        stem + ".tex",
    ]
    commands = [latex]
    if stem != OUTPUT_STEMS["industry"]:
        commands.append([tools["biber"], stem])
    # Subsequent passes settle citations, the table of contents and page totals.
    commands.extend((latex, latex))
    log_path = output_dir / (stem + ".build.log")
    pdf = output_dir / (stem + ".pdf")
    with (
        _preserve_pdf_on_failure(pdf),
        log_path.open("w", encoding="utf-8", newline="\n") as log,
    ):
        # First inspect normal pagination, then allow one complete corrective
        # compile cycle. Never silently loop if blank pages remain.
        for phase in range(2):
            for command in commands:
                print(f"Running {Path(command[0]).stem}...")
                log.write("$ " + subprocess.list2cmdline(command) + "\n")
                log.flush()
                try:
                    # An argument list handles executable paths with spaces
                    # directly; no shell expansion or command quoting is needed.
                    result = subprocess.run(
                        command,
                        cwd=output_dir,
                        env=environment,
                        stdout=subprocess.PIPE,
                        stderr=subprocess.STDOUT,
                        timeout=120,
                        check=False,
                    )
                except subprocess.TimeoutExpired as error:
                    if error.stdout:
                        log.write(error.stdout.decode("utf-8", errors="replace"))
                    raise RuntimeError(
                        f"Compilation timed out; see {log_path}"
                    ) from error
                transcript = result.stdout.decode("utf-8", errors="replace")
                log.write(transcript + "\n")
                if result.returncode:
                    print("\n".join(transcript.splitlines()[-25:]), file=sys.stderr)
                    raise RuntimeError(
                        f"{Path(command[0]).name} failed ({result.returncode}); see {log_path}"
                    )
            if not pdf.is_file():
                raise RuntimeError(f"Compilation did not produce {pdf}")
            empty_pages = find_empty_body_pages(pdf) if academic else ()
            if not empty_pages:
                break
            if phase:
                raise RuntimeError(
                    f"Empty body pages remain after recompilation: {empty_pages}; see {log_path}"
                )
            write_skip_pages(skip_path, empty_pages)
            print("Removing empty pages: " + ", ".join(map(str, empty_pages)))
            log.write(
                "Empty physical pages skipped: "
                + ", ".join(map(str, empty_pages))
                + "\n"
            )
    # Preserve previous outputs until a replacement has compiled successfully.
    if stem == OUTPUT_STEMS["current"]:
        cleanup_legacy_home(output_dir)
    return pdf


def main(argv: list[str] | None = None) -> int:
    """Dispatch explicit maintenance actions or generate and compile selected CVs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--date", help="CV reference date, YYYY-MM-DD (or SOURCE_DATE_EPOCH)"
    )
    parser.add_argument("--output-dir", default="gen", help="Output directory")
    parser.add_argument(
        "--activities", default="data/activities.csv", help="Local activities CSV"
    )
    parser.add_argument(
        "--format",
        choices=FORMAT_CHOICES,
        default=DEFAULT_FORMAT,
        help="Document format (default: all four)",
    )
    action = parser.add_mutually_exclusive_group()
    action.add_argument(
        "--tex-only", action="store_true", help="Generate TeX without compiling"
    )
    action.add_argument(
        "--clean", action="store_true", help="Remove known generated CV files"
    )
    action.add_argument(
        "--refresh-activities", action="store_true", help="Update the CSV snapshot only"
    )
    action.add_argument(
        "--check-tools", action="store_true", help="Check the TeX toolchain only"
    )
    args = parser.parse_args(argv)
    try:
        formats = selected_formats(args.format)
        required_tools = ("pdflatex",) if formats == ("industry",) else TOOLS
        output_dir = project_path(args.output_dir).resolve()
        if args.clean:
            clean(output_dir)
            print(f"Cleaned CV build products in {output_dir}")
            return 0
        if args.check_tools:
            for name, path in check_tools(required_tools).items():
                print(f"{name}: {path}")
            return 0
        if args.refresh_activities:
            from cvgen.acquisition import CSV_URL, refresh_activities

            destination = project_path(args.activities)
            refresh_activities(CSV_URL, destination)
            print(f"Updated {destination}; review the snapshot diff before rebuilding.")
            return 0
        # Resolve once for the entire invocation, including a build that
        # crosses midnight while compiling its four documents.
        as_of = resolve_date(args.date)
        epoch = source_epoch(as_of, explicit_date=args.date is not None)
        tools = None if args.tex_only else check_tools(required_tools)
        # Maintenance commands above need neither Jinja2 nor generation imports.
        from jinja2 import TemplateError

        from generate import generate

        for format in formats:
            stem = OUTPUT_STEMS[format]
            try:
                tex = generate(
                    output=output_dir / (stem + ".tex"),
                    activities=args.activities,
                    as_of=as_of,
                    format=format,
                )
            except TemplateError as error:
                raise ValueError(f"Invalid CV template: {error}") from error
            print(f"Generated {tex} (reference date {as_of.isoformat()})")
            if tools is not None:
                print(f"Built {compile_pdf(output_dir, tools, epoch, stem=stem)}")
    except (OSError, ValueError, KeyError, RuntimeError, csv.Error) as error:
        print(f"Build failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
